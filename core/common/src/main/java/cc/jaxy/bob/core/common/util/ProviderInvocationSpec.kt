/** Local chat implementations audited against model-runtime at 6c7a6fb033e443bc27bf34cbd5509ab3db7f22f3. */
fun providerAdapterType(providerId: String, protocol: String? = null, adapterType: String? = null): String? {
    val id = providerId.lowercase()
    if (id in NON_CHAT_PROVIDERS) return null
    return when (id) {
        "azure", "azureai", "bedrock", "vertexai", "cloudflare", "huggingface", "github",
        "chatgpt", "githubcopilot", "supergrok", "straico" -> id
        "anthropic", "kimicodingplan" -> "anthropic"
        "google" -> "google"
        "ollama", "ollamacloud" -> "ollama"
        "aihubmix", "zenmux", "newapi" -> "router"
        in OPENAI_PROVIDERS -> "openai"
        else -> protocol?.lowercase()?.takeIf { it in LOCAL_PROTOCOLS }
            ?: adapterType?.lowercase()?.takeIf { it in LOCAL_PROTOCOLS }
    }
}

